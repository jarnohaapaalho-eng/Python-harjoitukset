# Kirjoita ohjelma, joka kysyy kolme kokonaislukua. 
# Ohjelma tulostaa lukujen summan, tulon ja keskiarvon.

kokonaisluku_1 = int(input("Anna kokonaisluku: "))
kokonaisluku_2 = int(input("Ja toinen: "))
kokonaisluku_3 = int(input("Vielä kolmas: "))

print("Summa: ",kokonaisluku_1+kokonaisluku_2+kokonaisluku_3)
print("Tulo: ",kokonaisluku_1*kokonaisluku_2*kokonaisluku_3)
print("Keskiarvo: ",(kokonaisluku_1+kokonaisluku_2+kokonaisluku_3)/3)